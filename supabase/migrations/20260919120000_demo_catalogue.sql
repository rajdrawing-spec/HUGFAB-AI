-- ============================================================================
-- Demo catalogue — a labelled sample so the product can be used and reviewed
-- before an affiliate feed is approved.
--
-- WHY THIS IS A MIGRATION, NOT THE LOCAL SEED
-- The local seed is applied only by `supabase db reset` and never reaches a
-- hosted project. This data has to exist in production, so it travels the same
-- path as the schema: committed, reviewed, and applied by the database
-- workflow.
--
-- WHAT MAKES IT SAFE
--   * Every product row is `is_mock = true`. Every public surface already keys
--     off that column: the card shows a DEMO badge, the comparison table
--     refuses to render an outbound link, the sitemap omits the row and the
--     product page sets `robots: noindex`.
--   * Brands and retailers here are INVENTED. No real retailer's name appears
--     beside an invented price, because that would be a false statement about
--     that retailer — the one thing a price-comparison site must never make.
--     Their `website_url` points at example.com for the same reason.
--   * No affiliate URL is set on any row, so `affiliate_clicks` can never be
--     written from this data and no commission can be implied.
--
-- HOW TO TURN IT OFF
--   update public.app_settings set allow_mock_products = false where id;
-- That single row governs visibility for anon and authenticated through RLS.
-- The rows stay; nothing is deleted. To remove them entirely once a real feed
-- lands, delete where is_mock.
--
-- Idempotent throughout: re-applying changes nothing.
-- ============================================================================

